@router.post("/close/{signal_id}", response_model=Signal)
async def close_signal(signal_id: str) -> Signal:
    """
    Manually close a signal.
    """
    try:
        signal = await database.get_signal_by_id(signal_id)
        
        if not signal:
            raise HTTPException(status_code=404, detail=f"Signal with ID '{signal_id}' not found")
        
        # Update signal status
        signal.status = SignalStatus.CLOSED
        signal.closed_at = datetime.utcnow()
        
        updated_signal = await database.update_signal(signal)
        
        # Invalidate cache
        await cache.delete(f"signal:{signal_id}")
        await cache.delete_pattern("signals:*")
        
        return updated_signal
    
    except HTTPException:
        raise
    except Exception as e:
        logger.error(f"Error closing signal {signal_id}: {e}")
        raise HTTPException(status_code=500, detail=f"Error closing signal: {str(e)}")
