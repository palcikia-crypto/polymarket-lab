@router.get("/", response_model=List[Signal])
async def get_signals(
    limit: int = Query(100, ge=1, le=1000, description="Maximum number of signals to return"),
    offset: int = Query(0, ge=0, description="Offset for pagination"),
    signal_type: Optional[SignalType] = Query(None, description="Filter by signal type"),
    status: Optional[SignalStatus] = Query(None, description="Filter by signal status"),
    market_id: Optional[str] = Query(None, description="Filter by market ID"),
    min_edge: Optional[float] = Query(None, ge=0, le=1, description="Minimum edge value (0-1)"),
    sort_by: str = Query("created_at", description="Sort by field"),
    sort_order: str = Query("desc", description="Sort order (asc or desc)"),
    use_cache: bool = Query(True, description="Use cached data if available")
) -> List[Signal]:
    """
    Get a list of signals, optionally filtered.
    """
    try:
        cache_key = f"signals:{signal_type}:{status}:{market_id}:{min_edge}:{sort_by}:{sort_order}:{limit}:{offset}"
        
        if use_cache:
            cached_signals = await cache.get_signals(cache_key)
            if cached_signals:
                logger.info(f"Returning {len(cached_signals)} cached signals")
                return cached_signals
        
        # Get signals from database
        signals = await database.get_signals(
            limit=limit,
  
          offset=offset,
            signal_type=signal_type,
            status=status,
            market_id=market_id,
            min_edge=min_edge
        )
        
        # Sort signals
        reverse = sort_order.lower() == "desc"
        if sort_by == "edge":
            signals = sorted(signals, key=lambda x: getattr(x, 'edge', 0), reverse=reverse)
        elif sort_by == "created_at":
            signals = sorted(signals, key=lambda x: x.created_at, reverse=reverse)
        elif sort_by == "updated_at":
            signals = sorted(signals, key=lambda x: x.updated_at, reverse=reverse)
        
        # Cache the results
        if use_cache:
            await cache.set_signals(cache_key, signals)
        
        return signals[:limit]
    
    except Exception as e:
        logger.error(f"Error fetching signals: {e}")
        raise HTTPException(status_code=500, detail=f"Error fetching signals: {str(e)}")


@router.get("/{signal_id}", response_model=Signal)
async def get_signal_by_id(signal_id: str) -> Signal:
    """
    Get a specific signal by its ID.
    """
    try:
        cache_key = f"signal:{signal_id}"
        
        # Try cache first
        cached_signal = await cache.get_signal(cache_key)
        if cached_signal:
            return cached_signal
        
        # Get from database
        signal = await database.get_signal_by_id(signal_id)
        
        if not signal:
            raise HTTPException(status_code=404, detail=f"Signal with ID '{signal_id}' not found")
        
        # Cache the result
        await cache.set_signal(cache_key, signal)
        
        return signal
    
    except HTTPException:
        raise
    except Exception as e:
        logger.error(f"Error fetching signal {signal_id}: {e}")
        raise HTTPException(status_code=500, detail=f"Error fetching signal: {str(e)}")


